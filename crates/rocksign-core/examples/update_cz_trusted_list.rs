//! Refresh the built-in Czech trust anchors from the official Czech trusted list.
//!
//!     cargo run -p rocksign-core --example update_cz_trusted_list [-- path/to/TSL_CZ.xtsl]
//!
//! Takes every service of type CA/QC (issues qualified certificates) whose status is "granted"
//! and which is meant for e-signatures or e-seals, writes each certificate to
//! `anchors/cz/<sha256>.der`, and regenerates `src/anchors_cz.rs`.

use std::fmt::Write as _;

use anyhow::{Context, Result};
use rocksign_core::x509::{Certificate, base64_decode};

const TSL_URL: &str = "https://tsl.gov.cz/publ/TSL_CZ.xtsl";
const NS: &str = "http://uri.etsi.org/02231/v2#";

fn child<'a, 'i>(n: roxmltree::Node<'a, 'i>, name: &str) -> Option<roxmltree::Node<'a, 'i>> {
    n.children().find(|c| c.has_tag_name((NS, name)))
}

fn main() -> Result<()> {
    let xml = match std::env::args().nth(1) {
        Some(path) => std::fs::read_to_string(path)?,
        None => ureq::get(TSL_URL).call()?.body_mut().with_config().limit(32 << 20).read_to_string()?,
    };
    let doc = roxmltree::Document::parse(&xml).context("trusted list XML")?;
    let issued = doc.descendants().find(|n| n.has_tag_name((NS, "ListIssueDateTime"))).and_then(|n| n.text()).unwrap_or("?").to_string();

    let root = env!("CARGO_MANIFEST_DIR");
    let dir = format!("{root}/anchors/cz");
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir)?;
    let mut entries: Vec<(String, String, String)> = Vec::new(); // (provider, subject CN, file)

    for tsp in doc.descendants().filter(|n| n.has_tag_name((NS, "TrustServiceProvider"))) {
        let provider = tsp
            .descendants()
            .find(|n| n.has_tag_name((NS, "TSPName")))
            .and_then(|n| n.children().find(|c| c.is_element()))
            .and_then(|n| n.text())
            .unwrap_or("?")
            .to_string();
        for svc in tsp.descendants().filter(|n| n.has_tag_name((NS, "TSPService"))) {
            let Some(info) = child(svc, "ServiceInformation") else { continue };
            let text = |name: &str| child(info, name).and_then(|n| n.text()).unwrap_or("").to_string();
            if text("ServiceTypeIdentifier") != "http://uri.etsi.org/TrstSvc/Svctype/CA/QC" || !text("ServiceStatus").ends_with("/granted") {
                continue;
            }
            let uses: Vec<String> = info
                .descendants()
                .filter(|n| n.has_tag_name((NS, "AdditionalServiceInformation")))
                .filter_map(|n| child(n, "URI").and_then(|u| u.text()).map(str::to_string))
                .collect();
            if !uses.iter().any(|u| u.ends_with("/ForeSignatures") || u.ends_with("/ForeSeals")) {
                continue;
            }
            for c in info.descendants().filter(|n| n.has_tag_name((NS, "X509Certificate"))) {
                let der = base64_decode(c.text().unwrap_or(""))?;
                let cert = Certificate::parse(&der)?;
                let hex: String = cert.sha256_fingerprint().iter().map(|b| format!("{b:02x}")).collect();
                let file = format!("{hex}.der");
                if entries.iter().any(|e| e.2 == file) {
                    continue;
                }
                std::fs::write(format!("{dir}/{file}"), &der)?;
                entries.push((provider.clone(), cert.display_name(), file));
            }
        }
    }
    entries.sort();

    let mut src = String::new();
    writeln!(src, "// Generated by `cargo run -p rocksign-core --example update_cz_trusted_list`. Do not edit.")?;
    writeln!(src, "// Source: {TSL_URL} (list issued {issued}).")?;
    writeln!(src, "// CA/QC services with status \"granted\", for e-signatures or e-seals.\n")?;
    writeln!(src, "pub const LIST_ISSUED: &str = {issued:?};\n")?;
    writeln!(src, "/// (provider, CA name, DER certificate)")?;
    writeln!(src, "pub const CERTIFICATES: &[(&str, &str, &[u8])] = &[")?;
    for (provider, cn, file) in &entries {
        writeln!(src, "    ({provider:?}, {cn:?}, include_bytes!(\"../anchors/cz/{file}\")),")?;
    }
    writeln!(src, "];")?;
    std::fs::write(format!("{root}/src/anchors_cz.rs"), src)?;
    for (provider, cn, file) in &entries {
        println!("{provider:32} {cn:45} {}", &file[..16]);
    }
    println!("{} certificates from the list issued {issued}", entries.len());
    Ok(())
}
